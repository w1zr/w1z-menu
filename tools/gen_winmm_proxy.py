"""Generates the winmm.dll proxy sources from the system winmm.dll.

Writes (all checked in, regenerate only if Windows' winmm.dll exports change):
  src/winmm.def           exports with the same names and ordinals
  src/winmm_stubs.asm     one `jmp [table+i*8]` stub per export (ml64)
  src/winmm_exports.inc   C++ table of names/ordinals the loader resolves

usage: python tools/gen_winmm_proxy.py
"""
import os

import pefile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYSTEM = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "winmm.dll")


def main():
    pe = pefile.PE(SYSTEM)
    exports = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda e: e.ordinal)
    rows = []
    for i, e in enumerate(exports):
        name = e.name.decode() if e.name else None
        stub = f"Stub_{name}" if name else f"Stub_Ordinal{e.ordinal}"
        rows.append((i, e.ordinal, name, stub))

    with open(os.path.join(ROOT, "src", "winmm.def"), "w", newline="\r\n") as f:
        f.write("; Generated by tools/gen_winmm_proxy.py from the system winmm.dll. Do not edit.\n")
        f.write("LIBRARY winmm\nEXPORTS\n")
        for i, ordinal, name, stub in rows:
            if name:
                f.write(f"    {name}={stub} @{ordinal}\n")
            else:
                f.write(f"    {stub} @{ordinal} NONAME\n")

    with open(os.path.join(ROOT, "src", "winmm_stubs.asm"), "w", newline="\r\n") as f:
        f.write("; Generated by tools/gen_winmm_proxy.py from the system winmm.dll. Do not edit.\n")
        f.write("; Each export jumps through g_winmmTable, which proxy_winmm.cpp fills with the\n")
        f.write("; real System32 winmm.dll functions before anything can call them.\n\n")
        f.write("PUBLIC g_winmmTable\n\n.data\nALIGN 8\n")
        f.write(f"g_winmmTable QWORD {len(rows)} DUP(0)\n\n.code\n")
        for i, ordinal, name, stub in rows:
            f.write(f"{stub} PROC\n    jmp QWORD PTR [g_winmmTable + {i * 8}]\n{stub} ENDP\n")
        f.write("\nEND\n")

    with open(os.path.join(ROOT, "src", "winmm_exports.inc"), "w", newline="\r\n") as f:
        f.write("// Generated by tools/gen_winmm_proxy.py from the system winmm.dll. Do not edit.\n")
        f.write("// { name or nullptr for ordinal-only, ordinal } in g_winmmTable order.\n")
        for i, ordinal, name, stub in rows:
            n = f'"{name}"' if name else "nullptr"
            f.write(f"{{{n}, {ordinal}}},\n")

    print(f"{len(rows)} exports written")


if __name__ == "__main__":
    main()
